"""Write `reports/phase7_load_test.md` from the k6 results in `reports/loadtest/*.json` (`make loadtest`).

Every number in the report comes from those files; the k6 script (`loadtest/api.js`) says what each run does.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "reports" / "loadtest"
REPORT = ROOT / "reports" / "phase7_load_test.md"
RUNS = ("redis_up", "redis_down", "redis_down_light")
REQUESTS = {
    "valuation": "valuation `GET /players/{id}/valuation`",
    "search": "search `GET /players?q=`",
    "whatif": "what-if `POST /valuations`",
}
EXPECTATION = {
    "fast": "no errors, at most 1% shed with 503 \"busy\", and every p95 within its budget",
    "served": "every request answered 200",
    "shed": "only 200s and immediate 503 \"busy\" refusals, never a 500, and no response slower than the p99 bound",
}


def _ms(x: float | None) -> str:
    return "–" if x is None else f"{x:,.1f} ms"


def _pct(x: float | None) -> str:
    return "–" if x is None else f"{100 * x:.1f}%"


def _per_second(r: dict[str, Any], seconds: float, share: float | None) -> float:
    return r["any_ms"].get("count", 0) * (share or 0.0) / seconds


def _seconds(duration: str) -> float:
    return float(duration.rstrip("s"))


def build(runs: dict[str, dict[str, Any]]) -> str:
    first = runs[RUNS[0]]["meta"]
    cfg = first["api_config"]
    finished = max(r["meta"]["finished_at"] for r in runs.values())
    lines = [
        "# Phase 7: load test",
        "",
        (f"Generated by `make loadtest` (`scripts/loadtest.sh` → `loadtest/api.js` → `scripts/loadtest_report.py`) "
        f"on {finished[:10]}, code at `{first['git']}`. The numbers depend on the machine and on what else it is running, and vary "
        f"between runs on a shared laptop (the project log lists the range seen): rerun to compare."),
        "",
        "## Setup",
        "",
        (f"- **API:** the `Dockerfile.api` image with {cfg['workers']} uvicorn workers. Each worker takes at most "
        f"{cfg['max_concurrent_requests']} requests at once (more get an immediate 503 \"busy\") and has "
        f"{cfg['db_connections']} database connections, waited for at most {cfg['db_pool_timeout_s']:g} s."),
        (f"- **Machine:** Docker Desktop with {first['docker_cpus']} CPUs and "
        f"{int(first['docker_memory_bytes']) / 2**30:.1f} GiB, shared by the API, Postgres, Redis, k6 and any other running container."),
        (f"- **Load:** `{first['k6_image']}` on the same Docker network. It uses an open model (fixed arrival rates), "
        f"so a slow API faces a growing backlog, as it would with real users. {first['players']} players were found "
        f"through the search endpoint and their valuations cached in `setup()`. Valuations then come from Redis when "
        f"it is up, search is never cached, and every what-if is a new scenario, so always a cache miss (model + "
        f"TreeSHAP). The three request types run at the "
        f"same time for {_seconds(first['duration']):g} s per run. The per-IP what-if limit is lifted, because k6 is a single client."),
        "",
        "## Results",
        "",
        ("Latency columns cover the requests answered 200; the last latency column covers every response, "
        "refusals included."),
        "",
        ("| Run | Redis | Request | Target | Requests | Served | Shed (503) | Errors | p50 | p95 | p99 "
        "| All responses p99 | Cache hits |"),
        "|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for name in RUNS:
        run = runs[name]
        meta = run["meta"]
        for req, r in run["requests"].items():
            lines.append(
                f"| `{name}` | {meta['redis']} | {REQUESTS[req]} | {meta['rates_per_second'][req]}/s "
                f"| {r['any_ms'].get('count', 0):,} | {_pct(r['ok_rate'])} | {_pct(r['shed_rate'])} "
                f"| {_pct(r['error_rate'])} | {_ms(r['served_ms'].get('med'))} | {_ms(r['served_ms'].get('p(95)'))} "
                f"| {_ms(r['served_ms'].get('p(99)'))} | {_ms(r['any_ms'].get('p(99)'))} | {_pct(r['cache_hit_rate'])} |"
            )
    lines += ["", "## Pass/fail thresholds", ""]
    for name in RUNS:
        run = runs[name]
        rules = [(rule, passed) for r in run["requests"].values() for rule, passed in r["thresholds"].items()]
        verdict = "passed" if all(p for _, p in rules) else "FAILED"
        lines.append(f"- `{name}`, expecting {EXPECTATION[run['meta']['expect']]}: **{verdict}**")
        lines += [f"  - `{rule}`: {'pass' if passed else 'FAIL'}" for rule, passed in rules]
        if run["dropped_iterations"]:
            lines.append(f"  - k6 dropped {run['dropped_iterations']} requests it had no free virtual user to send")
    lines += ["", "## What the numbers say", ""]
    up, down, light = (runs[n] for n in RUNS)
    v_up, w_up = up["requests"]["valuation"], up["requests"]["whatif"]
    secs = _seconds(down["meta"]["duration"])
    served_down = sum(_per_second(r, secs, r["ok_rate"]) for r in down["requests"].values())
    offered_down = sum(down["meta"]["rates_per_second"].values())
    errors_down = sum(r["any_ms"].get("count", 0) * (r["error_rate"] or 0) for r in down["requests"].values())
    worst_down = max(r["any_ms"].get("p(99)", 0) for r in down["requests"].values())
    v_light = light["requests"]["valuation"]
    lines += [
        (f"- **With Redis**, cached valuations were served at a p95 of {_ms(v_up['served_ms'].get('p(95)'))} "
        f"({_pct(v_up['cache_hit_rate'])} cache hits). What-ifs, which always run the model and TreeSHAP, "
        f"took {_ms(w_up['served_ms'].get('p(95)'))} at p95."),
        (f"- **With Redis stopped at the same load**, every valuation had to be computed. The API served "
        f"{served_down:.0f} of the {offered_down} requests per second and refused the rest at once with 503 \"busy\". "
        f"{int(errors_down)} responses were errors, and 99% of all responses came back within {_ms(worst_down)}."),
        (f"- **With Redis stopped at a quarter of the load**, {_pct(v_light['ok_rate'])} of valuations were served "
        f"and nothing was refused: every valuation was computed, at a p95 of "
        f"{_ms(v_light['served_ms'].get('p(95)'))}."),
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    missing = [n for n in RUNS if not (RESULTS / f"{n}.json").exists()]
    if missing:
        sys.exit(f"missing k6 results for {', '.join(missing)}: run `make loadtest`")
    runs = {n: json.loads((RESULTS / f"{n}.json").read_text(encoding="utf-8")) for n in RUNS}
    REPORT.write_text(build(runs), encoding="utf-8")
    print(f"wrote {REPORT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
